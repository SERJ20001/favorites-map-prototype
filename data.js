export const money = (value) =>
  `${new Intl.NumberFormat("ru-RU").format(value)} ₽`;
export const distance = (product, origin) =>
  Math.round(Math.hypot(product.x - origin.x, product.y - origin.y) / 10) * 10;
export const distanceText = (meters) =>
  meters < 1000
    ? `${meters} м`
    : `${(meters / 1000).toFixed(1).replace(".", ",")} км`;
export const walkMinutes = (meters) => Math.max(1, Math.round(meters / 80));
